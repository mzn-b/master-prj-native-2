#!/usr/bin/env node
/**
 * Writes src/config/buildInfo.ts with an identifier for the build being made.
 *
 * `appVersion` used to be the hard-coded string "1.0.0" in both apps, so every
 * session looked like it came from the same build. Several behaviour-changing
 * fixes can land in a day — the MediaPipe orientation fix on 2026-09-11 changed
 * what the app measures — and without a stamp the sessions from before and after
 * are indistinguishable in the database.
 *
 * Runs automatically before `npm run android|ios|start` via npm's pre-scripts.
 * A build started directly from Xcode or Gradle will carry whatever stamp was
 * written last, so run `npm run stamp` first in that case.
 */
import { execSync } from "node:child_process";
import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function git(args) {
    try {
        return execSync(`git ${args}`, { cwd: root, stdio: ["ignore", "pipe", "ignore"] })
            .toString()
            .trim();
    } catch {
        return "";
    }
}

const pkgVersion = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version ?? "0.0.0";
const sha = git("rev-parse --short HEAD") || "nogit";
// A dirty tree means the build does not correspond to any commit, which matters
// more than the commit itself when tracing a measurement back to its code.
//
// The generated file below is excluded from that check, because it is tracked
// and this script rewrites it on every run (BUILT_AT alone always changes).
// Including it made the script dirty its own tree: the first stamp after a
// commit was clean, and every stamp after that reported "-dirty" with nothing
// actually modified. Since `preios`/`preandroid` run this, that meant building
// for the second platform silently produced a build the thesis cannot cite.
const GENERATED = "src/config/buildInfo.ts";
const dirty = git("status --porcelain")
    .split("\n")
    .map(line => line.trim())
    .filter(Boolean)
    // Porcelain lines are "XY path"; compare the path, not the status letters.
    .some(line => !line.slice(2).trim().endsWith(GENERATED))
    ? "-dirty"
    : "";
const builtAt = new Date().toISOString();

const out = `// GENERATED by scripts/stamp-build.mjs — do not edit.
export const APP_VERSION = '${pkgVersion}+${sha}${dirty}';
export const BUILT_AT = '${builtAt}';
`;

mkdirSync(join(root, "src/config"), { recursive: true });
writeFileSync(join(root, "src/config/buildInfo.ts"), out);
console.log(`[stamp-build] APP_VERSION=${pkgVersion}+${sha}${dirty}`);
