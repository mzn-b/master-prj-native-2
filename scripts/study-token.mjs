#!/usr/bin/env node
/**
 * Writes src/config/studyToken.generated.ts with the study's write token.
 *
 * The backend accepts a session only with this token (header X-Study-Token). It
 * must not enter the public repository, so it is read from the environment
 * variable STUDY_WRITE_TOKEN and written to a git-ignored file. Runs before
 * every build and before the tests (npm pre-scripts); the tests get an empty one.
 *
 * A survey build without it would run normally and lose every session to a 401,
 * so SURVEY_BUILD=1 without a token is refused.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const token = (process.env.STUDY_WRITE_TOKEN ?? "").trim();

if (process.env.SURVEY_BUILD === "1" && !token) {
    console.error("[study-token] SURVEY_BUILD=1 needs STUDY_WRITE_TOKEN (the value is in the backend's .env).");
    process.exit(1);
}

mkdirSync(join(root, "src/config"), { recursive: true });
writeFileSync(
    join(root, "src/config/studyToken.generated.ts"),
    "// GENERATED by scripts/study-token.mjs from STUDY_WRITE_TOKEN — git-ignored, do not commit.\n" +
    `export const STUDY_WRITE_TOKEN = ${JSON.stringify(token)};\n`,
);
console.log(`[study-token] ${token ? "write token set" : "no write token (sessions will be rejected)"}`);
