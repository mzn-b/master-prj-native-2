// Embeds binary assets that cannot be read at runtime into generated modules.
//
// crown.glb is parsed by three's GLTFLoader, which needs the raw bytes in JS.
// Reading it from the app bundle is not portable: in a Release build
// `Image.resolveAssetSource()` yields a real file URL on iOS but the bare
// Android resource name ("assets_filters_crown") on Android, which `fetch`
// cannot open — it fails with "Network request failed" and the crown silently
// renders nothing. Verified on a Pixel 7, 2026-10-08.
//
// Embedding gives both platforms the SAME code path, which is what NF4 wants:
// a platform branch here would be one more place the two arms could diverge
// without anyone noticing.
import {readFileSync, writeFileSync, mkdirSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const ASSETS = [
    {
        from: "assets/filters/crown.glb",
        to: "src/render/filters/crownGlb.generated.ts",
        constName: "CROWN_GLB_BASE64",
    },
];

for (const {from, to, constName} of ASSETS) {
    const bytes = readFileSync(join(root, from));
    const base64 = bytes.toString("base64");
    const out = `// GENERATED by scripts/embed-assets.mjs — do not edit, do not commit.
// Source: ${from} (${bytes.length} bytes)
export const ${constName} =
    '${base64}';
`;
    const target = join(root, to);
    mkdirSync(dirname(target), {recursive: true});
    writeFileSync(target, out);
    console.log(
        `[embed-assets] ${from} -> ${to} (${bytes.length} bytes -> ${base64.length} base64 chars)`,
    );
}
